%% Run the Eccentricity experiment

% work on storing position and font of the words 

function Data = Experiment_Whole_Eccentricity(varargin)
block = varargin{1};          % Current block number during the experiment 
Window = varargin{2};           % Window information such as ppd, centerX, centerY, etc
gTrialConds = varargin{3};    % (Generated trial conditions): Structure generated by the 'GenerateTrials_Eccentricity' script

KbQueueFlush(Window.KeyboardNum); 

fprintf('\n\n-----------------------Start of Block--------------------------\n\n'); 

%% Set up experiment parameters
Data = struct();
Data.Timing = struct();
Data.Timing.StimOnsets = [];
Data.Timing.StimOffsets = [];
Data.Timing.EpochOnsets = [];
Data.Timing.EpochOffsets = [];
Data.Epoch = {};
Data.Timing.BlankOnsets = []; 
Data.Timing.TR = [];  
% Data.FixationPos = [];
Data.Quit = 0;


flipTime = Window.frameTime;


%% Set up blocks 
% current_block = gTrialConds.Parameters.BlockNames{block};
% isFixationOnBlock = strcmp(current_block, 'Fixation_Moving');
% isFixationStaticBlock = strcmp(current_block, 'Fixation_Static');

%% Shuffle the order of epoch types

epoch_types = {'fovea_scenes', 'fovea_phase_scrambled', 'periphery_scenes', 'periphery_phase_scrambled'};
num_epoch_types = length(epoch_types);
shuffled_epochs = randperm(num_epoch_types);

%% %%%%%%%%%%%%%%%%%%%% Initialize screen %%%%%%%%%%%%%%%%%%%%

Screen('FillRect', Window.onScreen, Window.bcolor);
Screen('Flip', Window.onScreen);

%% Create fixation dot

% dotSize = 10;
% fixation_color = [255, 0, 0]; 

%% Define 8 fixation positions around the circle 
% fixationPositions = [Window.centerX - 150, Window.centerY;  
%                      Window.centerX + 150, Window.centerY;
%                      Window.centerX, Window.centerY - 150;
%                      Window.centerX, Window.centerY + 150;
%                      Window.centerX - 150, Window.centerY - 150;  % Top left diagonal
%                      Window.centerX + 150, Window.centerY - 150;  % Top right diagonal
%                      Window.centerX - 150, Window.centerY + 150;  % Bottom left diagonal
%                      Window.centerX + 150, Window.centerY + 150]; % Bottom right diagonal
% 
% numFixationPositions = size(fixationPositions, 1);
% shuffledIndices = randperm(numFixationPositions); 
% fixationIndex = 1;
% currentFixationPos = fixationPositions(shuffledIndices(fixationIndex), :);
% fixationLastChangeTime = GetSecs;
% fixationDuration = 3;  

%% Create textures 

image_width_deg_fovea = 6;      
image_width_deg_periphery = 40; 

% Convert image widths to pixels
image_width_px_fovea = image_width_deg_fovea * Window.ppd;
image_width_px_periphery = image_width_deg_periphery * Window.ppd;

%Screen('BlendFunction', Window.onScreen, 'GL_SRC_ALPHA', 'GL_ONE_MINUS_SRC_ALPHA');

%% Create words

% fonts = {'Arial', 'Times New Roman', 'Helvetica', 'Courier New', 'Verdana', ...
%          'Chalkboard', 'Comic Sans MS', 'Didot', 'Luminari', 'Tratello', 'Skia'};

%fonts = {'Monaco', 'LucidaBrightRegular'};

fonts = {...
    'DejaVuSans',...
    'DejaVuSans-Bold',...
    'FreeSans',...
    'FreeMono',...
    'FreeSerif',...
    'LiberationSans-Regular',...
    'NotoSans-Bold'...
    };

shuffledFonts = Shuffle(fonts);
fontIndex = 1;

%% Generate image pairs within fovea and periphery for yoking 

% Load stimuli paths 
scenes_intact_Dir = gTrialConds.scenes_intact_Dir;
scenes_intact_Files = gTrialConds.scenes_intact_Files;
phase_scrambled_scenesDir = gTrialConds.phase_scrambled_scenesDir;
phase_scrambled_sceneFiles = gTrialConds.phase_scrambled_sceneFiles;

% Make sure filenames are in same order so you can match them later 
intact_filenames = sort({scenes_intact_Files.name});
scrambled_filenames = sort({phase_scrambled_sceneFiles.name});

% Match the same images from both folders 
common_filenames = intersect(intact_filenames, scrambled_filenames);

% Number of images per condition
num_images_per_condition = gTrialConds.Parameters.num_trials_per_epoch * 2;

% Randomly select images for fovea conditions
selected_indices_fovea = randperm(length(common_filenames), num_images_per_condition);
selected_filenames_fovea = common_filenames(selected_indices_fovea);

% Remove the selected images from the list
remaining_indices = setdiff(1:length(common_filenames), selected_indices_fovea);

% Select images for periphery conditions from the remaining images
selected_indices_periphery = remaining_indices(randperm(length(remaining_indices), num_images_per_condition));
selected_filenames_periphery = common_filenames(selected_indices_periphery);

%% Pair the intact and phase scrambled versions of each image

% Create image pairs for fovea conditions
imagePairs_fovea = cell(length(selected_filenames_fovea), 2);
for i = 1:length(selected_filenames_fovea)
    filename = selected_filenames_fovea{i};
    imagePairs_fovea{i, 1} = fullfile(scenes_intact_Dir, filename);  % Intact path
    imagePairs_fovea{i, 2} = fullfile(phase_scrambled_scenesDir, filename); % Scrambled path
end

% Create image pairs for periphery conditions
imagePairs_periphery = cell(length(selected_filenames_periphery), 2);
for i = 1:length(selected_filenames_periphery)
    filename = selected_filenames_periphery{i};
    imagePairs_periphery{i, 1} = fullfile(scenes_intact_Dir, filename);  % Intact path
    imagePairs_periphery{i, 2} = fullfile(phase_scrambled_scenesDir, filename); % Scrambled path
end

%% Generate image orders for fovea and periphery
num_pairs_fovea = size(imagePairs_fovea, 1);
num_pairs_periphery = size(imagePairs_periphery, 1);

imageOrder_fovea = Shuffle(1:num_pairs_fovea);
imageOrder_periphery = Shuffle(1:num_pairs_periphery);

num_trials_per_epoch = gTrialConds.Parameters.num_trials_per_epoch;

imageOrder_fovea = imageOrder_fovea(1:num_trials_per_epoch);
imageOrder_periphery = imageOrder_periphery(1:num_trials_per_epoch);

%% Wait for scanner trigger before starting the experiment

% If the scanner is running it will wait 1 TR to begin, if it is not
% running but could be then it will hang until a burn has completed. If
% there is no scanner connected then 
[Data.Timing.TR, Quit] = Setup_WaitingForScanner(Window);

Window.EyeTracking = Utils_EyeTracker_Message(Window.EyeTracking, sprintf('Start_of_Block_Time:_%0.3f', GetSecs));

% Calculate when is the next TR expected
if ~isempty(Data.Timing.TR)
    NextTR=Data.Timing.TR(end)+Window.TR;
else
    NextTR=Window.NextTR;
end

%% Begin experiment 

% When did the experiment begin
Data.Timing.TestStart=GetSecs;

block_start_time = GetSecs;
block_duration = gTrialConds.Parameters.block_duration;

% fprintf('\nRunning block %s: %0.3f seconds\n', current_block, block_start_time - Data.Timing.TestStart);
fprintf('\nRunning block %s: %0.3f seconds\n', block_start_time - Data.Timing.TestStart);

%% Run each of the 4 epoch types 

for epoch_idx = 1:num_epoch_types
    if Quit == 1
        break;  % Exit loop if 'q' was pressed
    end
    
    
    current_epoch_idx = shuffled_epochs(epoch_idx);
    current_epoch = epoch_types{current_epoch_idx};
    
    % Store each epoch label 
    Data.Epoch{end + 1} = current_epoch;
    
    %% Which image set is used
    
    if contains(current_epoch, 'fovea')
        imagePairs = imagePairs_fovea;
        imageOrder = imageOrder_fovea;
    elseif contains(current_epoch, 'periphery')
        imagePairs = imagePairs_periphery;
        imageOrder = imageOrder_periphery;
    end
    
    %% Set the duration of each trial
    trial_duration = gTrialConds.Parameters.stim_duration + gTrialConds.Parameters.stim_duration_off;


    %% Start the eye tracker for this epoch type 
    Window.EyeTracking = Utils_EyeTracker_Message(Window.EyeTracking, ...
        sprintf('Start_of_Epoch_%s_Time:_%0.3f', current_epoch, GetSecs));
    Utils_EyeTracker_TrialStart(Window.EyeTracking);
    
    % Record the start time of the epoch
    Data.Timing.EpochOnsets(epoch_idx) = GetSecs;
    
    flipTime = Window.frameTime;
    
    % Calculate the time since the experiment started
    epoch_time = Data.Timing.EpochOnsets(epoch_idx) - Data.Timing.TestStart;
    
    % Print the epoch name and start time
    fprintf('\nRunning epoch type %s (Epoch %d of %d): %0.3f seconds\n', current_epoch, epoch_idx, num_epoch_types, epoch_time); 
    
    
    %% Run each of the 14 stimuli 
    for trial_idx = 1:gTrialConds.Parameters.num_trials_per_epoch   
        
        if Quit == 1
            break;  % Exit loop if 'q' was pressed
        end
        %% Calculate the expected start time for the current trial 
       
        expected_trial_start = block_start_time + (trial_idx - 1) * trial_duration + ((epoch_idx - 1) * (gTrialConds.Parameters.num_trials_per_epoch * trial_duration)) + gTrialConds.Parameters.stim_duration_off;

        
        %% Present blank screen for 300ms 
        Window.EyeTracking = Utils_EyeTracker_Message(Window.EyeTracking, sprintf('ISI_On:_%0.3f', GetSecs));
        
        Screen('FillRect', Window.onScreen, Window.bcolor); 
        
        % isFixationMoving = (isFixationOnBlock && contains(current_epoch, 'periphery') && strcmp(current_block, 'Fixation_Moving'));
        % isFixationStatic = (isFixationStaticBlock && contains(current_epoch, 'periphery') && strcmp(current_block, 'Fixation_Static'));
        % 
        % if isFixationMoving && contains(current_epoch, 'periphery')
        %     Screen('DrawDots', Window.onScreen, currentFixationPos', dotSize, fixation_color, [], 2);
        % end
        
        % if isFixationStatic && contains(current_epoch, 'periphery')
        %     Screen('DrawDots', Window.onScreen, [Window.centerX; Window.centerY]', dotSize, fixation_color, [], 2);
        % end
        
        
        %blank_onset = Screen('Flip', Window.onScreen, expected_trial_start + gTrialConds.Parameters.stim_duration);
        blank_onset = Screen('Flip', Window.onScreen);
        Data.Timing.BlankOnsets(end+1) = blank_onset;
        
        %% Get the index for the current trial
        
        idx = imageOrder(trial_idx);
        
        if contains(current_epoch, 'phase_scrambled')
            imgPath = imagePairs{idx, 2}; % Load phase-scrambled image
        else
            imgPath = imagePairs{idx, 1}; % Load intact image
        end
        
        
        %% Make sure that yoking is working
        fprintf('Presenting Image for Trial %d in Epoch "%s": %s\n', trial_idx, current_epoch, imgPath);
        
        %% Now, load the image! 
        img = imread(imgPath);
            
        [rows, cols, ~] = size(img);
        
        %% Overlay text 
        
        if contains(current_epoch, 'phase_scrambled')
            currentFont = shuffledFonts{fontIndex};
            fontIndex = fontIndex + 1;

            % Reshuffle and start over
            if fontIndex > length(shuffledFonts)
                shuffledFonts = Shuffle(fonts);
                fontIndex = 1;
            end
        
       
            latinParagraph = 'HomoinvitasaepequaeritsensumrerumetrationemexistendiNaturaispacumsuismysteriisetpulchritudinehominemadcogitationemprofundamducitStellaeincaelonocturnolucentesmontesexcelsiquiadcaelosattollunturetfluctusoceaniperpetuocurrentestestanturdemagnitudineuniversietparvitatehominisSedtamenhomolicetparvussingularisingeniifacultathemquainvestigatetcomprehenditlegesnaturalesetipsamcondicionemhumanamSapientianonexdivitiisnequeexpotentianascitursedexhumilitatelaboreassiduoetamoreveritatisQuiadscientiametvirtutemaspirateumfortunaadiuvatetanimiFirmitassustinetTempusautemsemperfluensetirreversibilenosmonetutnonsolumdiscamussedetiamvivamusAmoramicitiaetdesideriumbonitatissuntquaevitamnostramplenamfaciuntItaquequaecumquedifficiliasintitineravitæspemetconstantiamretineredebemusuttandemadfinemnostrumperveniamusnobilesetintegri';
            snippetLength = 200;  % Number of characters you want in the snippet
            maxStartIndex = length(latinParagraph) - snippetLength;
            startIndex = randi(maxStartIndex);  % Random starting point

            % Extract the snippet from the paragraph
            randomSnippet = latinParagraph(startIndex:startIndex + snippetLength - 1);

            charsPerLine = 20;
            numLines = ceil(length(randomSnippet) / charsPerLine);
            lines = cell(numLines, 1);

            for i = 1:numLines
                startIdx = (i-1) * charsPerLine + 1;
                endIdx = min(i * charsPerLine, length(randomSnippet));
                lines{i} = randomSnippet(startIdx:endIdx);
            end 


            currentFontSize = 100;
            textColor = 'black';
            boxOpacity = 0;
            position = [cols / 2, rows / 2]; 
            
            lineHeight = currentFontSize * 0.8;  
            totalTextHeight = numLines * lineHeight;
            startY = (rows / 2) - (totalTextHeight / 2) + (lineHeight / 2);

            % Overlay each line onto the image
            for i = 1:numLines
                position = [cols / 2, startY + (i - 1) * lineHeight];
                img = insertText(img, position, lines{i}, ...
                    'Font', currentFont, 'FontSize', currentFontSize, ...
                    'TextColor', textColor, 'BoxOpacity', boxOpacity, ...
                    'AnchorPoint', 'Center');
            end
            
        end 
        
        %% Apply the circular mask and set background to Window.bcolor
        % Create the circular mask
        [X, Y] = meshgrid(1:cols, 1:rows);
        centerX = cols / 2;
        centerY = rows / 2;
        radius = min(centerX, centerY);
        mask = (X - centerX).^2 + (Y - centerY).^2 <= radius^2;

        % Convert scalar to 1x3 RGB vector
        if numel(Window.bcolor) == 1
            background_color = repmat(Window.bcolor, 1, 3);  
        elseif numel(Window.bcolor) == 3
            background_color = Window.bcolor;  
        else
            error('Background color needs to be in 1x3 format!!');
        end

        % Create a 3D mask
        mask3D = repmat(mask, [1, 1, 3]);

        % Create a background image matching the size of img
        background_image = uint8(zeros(size(img)));
        for c = 1:3
            background_image(:, :, c) = background_color(c);
        end

        % Apply the mask to the image
        img = img .* uint8(mask3D) + background_image .* uint8(~mask3D);
        
        % Now, create the texture without blending functions
        tex = Screen('MakeTexture', Window.onScreen, img);
        

        if contains(current_epoch, 'fovea')
            presentation = [Window.centerX - (image_width_px_fovea / 2), ...
                Window.centerY - (image_width_px_fovea / 2), ...
                Window.centerX + (image_width_px_fovea / 2), ...
                Window.centerY + (image_width_px_fovea / 2)];

            Screen('DrawTexture', Window.onScreen, tex, [], presentation);

            
        elseif contains(current_epoch, 'periphery')
            presentation = [Window.centerX - (image_width_px_periphery / 2), ...
                Window.centerY - (image_width_px_periphery / 2), ...
                Window.centerX + (image_width_px_periphery / 2), ...
                Window.centerY + (image_width_px_periphery / 2)];

            Screen('DrawTexture', Window.onScreen, tex, [], presentation);

        end
        
        %% Define dot position and presentation
        
        % isFixationMoving = (isFixationOnBlock && contains(current_epoch, 'periphery') && strcmp(current_block, 'Fixation_Moving'));
        % isFixationStatic = (isFixationStaticBlock && contains(current_epoch, 'periphery') && strcmp(current_block, 'Fixation_Static'));
        % 
        % if isFixationMoving 
        %     Screen('DrawDots', Window.onScreen, currentFixationPos', dotSize, fixation_color, [], 2);
        % end 
        % 
        % if isFixationStatic
        %     Screen('DrawDots', Window.onScreen, [Window.centerX; Window.centerY], dotSize, fixation_color, [], 2);
        % end 
            
        % Record the onset time
        stim_onset = Screen('Flip', Window.onScreen, expected_trial_start);
        Data.Timing.StimOnsets(end+1) = stim_onset;
        Screen('Close', tex);
        
        
        % if isFixationOnBlock
        %     if (GetSecs - fixationLastChangeTime) >= fixationDuration
        %         fixationIndex = fixationIndex + 1;
        %         if fixationIndex > numFixationPositions
        %             fixationIndex = 1;
        %             shuffledIndices = randperm(numFixationPositions); % Reshuffle the fixation positions
        %         end
        %         currentFixationPos = fixationPositions(shuffledIndices(fixationIndex), :);
        %         fixationLastChangeTime = GetSecs;
        %     end
        % else
        %     currentFixationPos = [NaN, NaN];
        % end
        % 
        % Data.FixationPos(end + 1, :) = currentFixationPos;
        
        while GetSecs < (expected_trial_start + gTrialConds.Parameters.stim_duration - flipTime) && (Quit == 0)

            [keyIsDown,keyCode_onset] = KbQueueCheck(Window.KeyboardNum);
        
            %If they have pressed q then quit
            if (keyIsDown) && sum(keyCode_onset>0)==1 && strcmp(KbName(keyCode_onset>0), 'q')
                Quit=1;
            end
            
            % if isFixationOnBlock
            %     if (GetSecs - fixationLastChangeTime) >= fixationDuration
            %         fixationIndex = fixationIndex + 1;
            %         if fixationIndex > numFixationPositions
            %             fixationIndex = 1;
            %         end
            %         currentFixationPos = fixationPositions(fixationIndex, :);
            %         fixationLastChangeTime = GetSecs;
            %     end
            % end
                   
            % Monitor TR pulses at the start of each superblock to synchronize
            % experiment with scanner timing 
            TRRecording = Utils_checkTrigger(NextTR, Window.ScannerNum);
            % Update expected next TR time
            if any(TRRecording > 0)
                Data.Timing.TR(end+1:end+length(TRRecording)) = TRRecording;
                NextTR = max(TRRecording) + Window.TR;
            end

        end 

    end 
        
    % Stop the eye tracker for this epoch
    Window.EyeTracking = Utils_EyeTracker_Message(Window.EyeTracking, ...
        sprintf('End_of_Epoch_%s_Time:_%0.3f', current_epoch, GetSecs));
    Utils_EyeTracker_TrialEnd(Window.EyeTracking);
    
    Data.Timing.EpochOffsets(epoch_idx) = GetSecs;

    
end

Window.EyeTracking = Utils_EyeTracker_Message(Window.EyeTracking, sprintf(['End_of_Block_Time_' num2str(GetSecs)]));
Utils_EyeTracker_TrialEnd(Window.EyeTracking);
DecayLapse = gTrialConds.Parameters.DecayLapse;

% Record block end time
Data.Timing.TestEnd = GetSecs;
Data.Timing.DecayLapse = DecayLapse + Data.Timing.TestEnd;
Data.Quit = Quit; 

% End of block
Screen('FillRect', Window.onScreen, Window.bcolor);
Screen('Flip', Window.onScreen);
fprintf('\n\n -----------------------End of Block-------------------------- \n\n');

end